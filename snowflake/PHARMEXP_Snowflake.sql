    BATCH_ID NUMBER(38,0),
    MEDICINE_ID NUMBER(38,0),
    WAREHOUSE_ID NUMBER(38,0),
    BATCH_NUMBER VARCHAR(100),
    MANUFACTURING_DATE DATE,
    EXPIRY_DATE DATE,
    RECEIVED_QUANTITY NUMBER(38,0),
    QUANTITY_ON_HAND NUMBER(38,0),
    QUANTITY_RESERVED NUMBER(38,0),
    QUANTITY_QUARANTINED NUMBER(38,0),
    UNIT_COST NUMBER(12,2),
    BATCH_STATUS VARCHAR(50),
    CREATED_AT TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ
