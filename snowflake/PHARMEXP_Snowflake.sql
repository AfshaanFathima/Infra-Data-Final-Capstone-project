-- ============================================================
-- 2. CONNECT SNOWFLAKE TO AWS S3
-- ============================================================
-- Run DESC INTEGRATION after creating the integration.
-- Copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID from its output.
-- Add them to the AWS IAM role trust relationship before continuing to the stage.

CREATE STORAGE INTEGRATION IF NOT EXISTS PHARMEXP_S3_INT
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = S3
    ENABLED = TRUE
    STORAGE_AWS_ROLE_ARN =
        'Your_ARN'
    STORAGE_ALLOWED_LOCATIONS =
        ('s3_Storage _Location');

DESC INTEGRATION PHARMEXP_S3_INT;

-- If the permitted S3 folder needs to be updated:
ALTER STORAGE INTEGRATION PHARMEXP_S3_INT
    SET STORAGE_ALLOWED_LOCATIONS =
        ('S3_storage_location');


-- ============================================================
-- 3. CREATE CSV FILE FORMAT AND EXTERNAL STAGE
-- ============================================================

USE DATABASE PHARMEXP_DB;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS PHARMEXP_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('', 'NULL', 'null');

CREATE STAGE IF NOT EXISTS PHARMEXP_S3_STAGE
    URL = 's3://pharmexp-cleaned-data-afshaan-2026/cleaned/'
    STORAGE_INTEGRATION = PHARMEXP_S3_INT
    FILE_FORMAT = PHARMEXP_CSV_FORMAT;

-- Confirm that Snowflake can see the eight cleaned CSV files.
LIST @PHARMEXP_S3_STAGE;


