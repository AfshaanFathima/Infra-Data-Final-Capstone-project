-- 7. CREATE THE SIX ANALYTICS VIEWS
-- ============================================================

USE DATABASE PHARMEXP_DB;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW VW_INVENTORY_OVERVIEW AS
SELECT
    m.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    w.WAREHOUSE_ID,
    w.WAREHOUSE_NAME,
    w.CITY,
    b.BATCH_ID,
    b.BATCH_NUMBER,
    b.MANUFACTURING_DATE,
    b.EXPIRY_DATE,
    b.BATCH_STATUS,
    b.RECEIVED_QUANTITY,
    b.QUANTITY_ON_HAND,
    b.QUANTITY_RESERVED,
    b.QUANTITY_QUARANTINED,
    b.UNIT_COST,
    CASE
        WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 0
        ELSE GREATEST(
            b.QUANTITY_ON_HAND - b.QUANTITY_RESERVED - b.QUANTITY_QUARANTINED,
            0
        )
    END AS AVAILABLE_STOCK,
    CASE
        WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 0
        ELSE GREATEST(
            b.QUANTITY_ON_HAND - b.QUANTITY_RESERVED - b.QUANTITY_QUARANTINED,
            0
        ) * b.UNIT_COST
    END AS INVENTORY_VALUE
FROM PHARMEXP_DB.RAW.INVENTORY_BATCHES b
LEFT JOIN PHARMEXP_DB.RAW.MEDICINES m
    ON b.MEDICINE_ID = m.MEDICINE_ID
LEFT JOIN PHARMEXP_DB.RAW.WAREHOUSES w
    ON b.WAREHOUSE_ID = w.WAREHOUSE_ID;


CREATE OR REPLACE VIEW VW_EXPIRY_ANALYSIS AS
SELECT
    b.BATCH_ID,
    b.BATCH_NUMBER,
    b.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    b.WAREHOUSE_ID,
    w.WAREHOUSE_NAME,
    w.CITY,
    b.MANUFACTURING_DATE,
    b.EXPIRY_DATE,
    b.QUANTITY_ON_HAND,
    b.QUANTITY_RESERVED,
    b.QUANTITY_QUARANTINED,
    DATEDIFF(DAY, CURRENT_DATE(), b.EXPIRY_DATE) AS DAYS_TO_EXPIRY,
    CASE
        WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 'EXPIRED'
        WHEN b.EXPIRY_DATE <= DATEADD(DAY, 90, CURRENT_DATE()) THEN 'NEAR EXPIRY'
        ELSE 'SAFE'
    END AS EXPIRY_STATUS,
    CASE
        WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 0
        ELSE GREATEST(
            b.QUANTITY_ON_HAND - b.QUANTITY_RESERVED - b.QUANTITY_QUARANTINED,
            0
        )
    END AS USABLE_STOCK
FROM PHARMEXP_DB.RAW.INVENTORY_BATCHES b
LEFT JOIN PHARMEXP_DB.RAW.MEDICINES m
    ON b.MEDICINE_ID = m.MEDICINE_ID
LEFT JOIN PHARMEXP_DB.RAW.WAREHOUSES w
    ON b.WAREHOUSE_ID = w.WAREHOUSE_ID;



CREATE OR REPLACE VIEW VW_WAREHOUSE_ANALYSIS AS
SELECT
    w.WAREHOUSE_ID,
    w.WAREHOUSE_CODE,
    w.WAREHOUSE_NAME,
    w.CITY,
    w.STATE,
    w.IS_ACTIVE,
    COUNT(b.BATCH_ID) AS TOTAL_BATCHES,
    COUNT(DISTINCT b.MEDICINE_ID) AS DISTINCT_MEDICINES,
    COALESCE(SUM(b.QUANTITY_ON_HAND), 0) AS TOTAL_STOCK_ON_HAND,
    COALESCE(SUM(b.QUANTITY_RESERVED), 0) AS TOTAL_RESERVED_STOCK,
    COALESCE(SUM(b.QUANTITY_QUARANTINED), 0) AS TOTAL_QUARANTINED_STOCK,
    COALESCE(SUM(
        CASE
            WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 0
            ELSE GREATEST(
                b.QUANTITY_ON_HAND - b.QUANTITY_RESERVED - b.QUANTITY_QUARANTINED,
                0
            )
        END
    ), 0) AS TOTAL_AVAILABLE_STOCK,
    COALESCE(SUM(
        CASE
            WHEN b.EXPIRY_DATE < CURRENT_DATE() THEN 0
            ELSE GREATEST(
                b.QUANTITY_ON_HAND - b.QUANTITY_RESERVED - b.QUANTITY_QUARANTINED,
                0
            ) * b.UNIT_COST
        END
    ), 0) AS TOTAL_INVENTORY_VALUE
FROM PHARMEXP_DB.RAW.WAREHOUSES w
LEFT JOIN PHARMEXP_DB.RAW.INVENTORY_BATCHES b
    ON w.WAREHOUSE_ID = b.WAREHOUSE_ID
GROUP BY
    w.WAREHOUSE_ID,
    w.WAREHOUSE_CODE,
    w.WAREHOUSE_NAME,
    w.CITY,
    w.STATE,
    w.IS_ACTIVE;



CREATE OR REPLACE VIEW VW_CONSUMPTION_DEMAND AS
SELECT
    m.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    w.WAREHOUSE_ID,
    w.WAREHOUSE_NAME,
    DATE_TRUNC('MONTH', c.CONSUMPTION_DATE) AS CONSUMPTION_MONTH,
    SUM(c.CONSUMED_QUANTITY) AS TOTAL_CONSUMED_QUANTITY,
    COUNT(c.CONSUMPTION_ID) AS CONSUMPTION_TRANSACTIONS,
    AVG(c.CONSUMED_QUANTITY) AS AVERAGE_QUANTITY_PER_TRANSACTION
FROM PHARMEXP_DB.RAW.MEDICINE_CONSUMPTION c
LEFT JOIN PHARMEXP_DB.RAW.MEDICINES m
    ON c.MEDICINE_ID = m.MEDICINE_ID
LEFT JOIN PHARMEXP_DB.RAW.WAREHOUSES w
    ON c.WAREHOUSE_ID = w.WAREHOUSE_ID
GROUP BY
    m.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    w.WAREHOUSE_ID,
    w.WAREHOUSE_NAME,
    DATE_TRUNC('MONTH', c.CONSUMPTION_DATE);



CREATE OR REPLACE VIEW VW_RESERVATIONS_ANALYSIS AS
SELECT
    r.RESERVATION_ID,
    r.RESERVATION_CODE,
    r.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    r.REQUESTED_QUANTITY,
    r.ALLOCATED_QUANTITY,
    r.CUSTOMER_REFERENCE,
    r.STATUS,
    r.REQUESTED_AT,
    r.EXPIRES_AT,
    r.NOTES,
    COALESCE(a.ALLOCATION_RECORDS, 0) AS ALLOCATION_RECORDS,
    COALESCE(a.BATCH_ALLOCATED_QUANTITY, 0) AS BATCH_ALLOCATED_QUANTITY
FROM PHARMEXP_DB.RAW.RESERVATIONS r
LEFT JOIN PHARMEXP_DB.RAW.MEDICINES m
    ON r.MEDICINE_ID = m.MEDICINE_ID
LEFT JOIN (
    SELECT
        RESERVATION_ID,
        COUNT(ALLOCATION_ID) AS ALLOCATION_RECORDS,
        SUM(ALLOCATED_QUANTITY) AS BATCH_ALLOCATED_QUANTITY
    FROM PHARMEXP_DB.RAW.RESERVATION_ALLOCATIONS
    GROUP BY RESERVATION_ID
) a
    ON r.RESERVATION_ID = a.RESERVATION_ID;



CREATE OR REPLACE VIEW VW_STOCK_TRANSFERS_ANALYSIS AS
SELECT
    t.TRANSFER_ID,
    t.MEDICINE_ID,
    m.MEDICINE_CODE,
    m.GENERIC_NAME,
    m.BRAND_NAME,
    t.SOURCE_WAREHOUSE_ID,
    sw.WAREHOUSE_NAME AS SOURCE_WAREHOUSE,
    t.DESTINATION_WAREHOUSE_ID,
    dw.WAREHOUSE_NAME AS DESTINATION_WAREHOUSE,
    t.SUGGESTED_QUANTITY,
    t.TRANSFER_REASON,
    t.STATUS,
    t.REVIEWED_BY,
    t.REVIEWED_AT,
    t.RECOMMENDATION_DATE,
    t.CREATED_AT,
    t.UPDATED_AT
FROM PHARMEXP_DB.RAW.STOCK_TRANSFERS t
LEFT JOIN PHARMEXP_DB.RAW.MEDICINES m
    ON t.MEDICINE_ID = m.MEDICINE_ID
LEFT JOIN PHARMEXP_DB.RAW.WAREHOUSES sw
    ON t.SOURCE_WAREHOUSE_ID = sw.WAREHOUSE_ID
LEFT JOIN PHARMEXP_DB.RAW.WAREHOUSES dw
    ON t.DESTINATION_WAREHOUSE_ID = dw.WAREHOUSE_ID;


